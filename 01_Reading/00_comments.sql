¿Qué son los comentarios?
Los comentarios son líneas de texto que el motor SQL IGNORA al ejecutar un script.
Se utilizan para dejar notas, explicaciones o recordatorios dentro del código,
para que sea más fácil de entender en el futuro (por mí o por otros desarrolladores).

->Tipos de comentarios en SQL:

Comentario de UNA línea (dos guiones):
------------------------------------------------
-- Esto es un comentario de una sola línea
SELECT * FROM usuarios;  -- También puedes escribirlo al final de una instrucción

Comentario de VARIAS líneas (bloque):
------------------------------------------------
/*
Este es un comentario que puede abarcar
varias líneas. Es útil para explicar
bloques grandes de código o secciones completas.
*/